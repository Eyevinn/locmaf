#!/usr/bin/env node
/*
 * Build a self-contained version of the LOCMAF Marp theme.
 *
 * themes/locmaf.css references the brand font and the two logos with relative
 * `url('../assets/...')` paths. marp-cli resolves those fine, because
 * .marprc.yml registers the theme from inside web/. The VS Code Marp preview
 * does not: it loads a registered theme by absolute path, the relative URLs no
 * longer resolve, and the deck renders without the LevelOne font or the
 * logomark.
 *
 * This inlines those three assets as base64 data URIs, producing
 * themes/locmaf.standalone.css — the file to register in
 * `markdown.marp.themes`.
 *
 * The output embeds a licensed brand font and is deliberately git-ignored:
 * it is a local build artifact, not something this public repo ships. Run
 * `npm run build:theme` after editing themes/locmaf.css.
 *
 * Adapted from ev-marp/scripts/build-standalone-theme.mjs.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..');

const SRC = join(web, 'themes', 'locmaf.css');
const OUT = join(web, 'themes', 'locmaf.standalone.css');

// Relative asset path as written in the CSS -> [file on disk, mime type].
const ASSETS = {
  '../assets/LevelOne.otf': ['assets/LevelOne.otf', 'font/otf'],
  '../assets/logomark-dark.svg': ['assets/logomark-dark.svg', 'image/svg+xml'],
  '../assets/eyevinn-logo.png': [optimisedLogo(), 'image/png'],
};

/*
 * assets/eyevinn-logo.png is 8333x2374 but the theme draws it 28px tall, so
 * inlining it verbatim would add ~950 KB of base64 to every preview render.
 * Downscale once into a git-ignored cache (sips ships with macOS). Without
 * sips we still build, just fat — correctness first, size second.
 */
function optimisedLogo() {
  const src = 'assets/eyevinn-logo.png';
  const out = 'assets/generated/eyevinn-logo-small.png';
  if (existsSync(join(web, out))) return out;
  mkdirSync(join(web, 'assets', 'generated'), { recursive: true });
  const r = spawnSync('sips', ['-Z', '700', join(web, src), '--out', join(web, out)],
    { stdio: 'ignore' });
  if (r.status === 0 && existsSync(join(web, out))) return out;
  console.warn(`WARNING: could not downscale ${src} (sips unavailable) — embedding full size.`);
  return src;
}

const dataUri = (rel, mime) => {
  const file = join(web, rel);
  if (!existsSync(file)) {
    console.error(`ERROR: missing asset ${rel}`);
    process.exit(1);
  }
  return `data:${mime};base64,${readFileSync(file).toString('base64')}`;
};

let css = readFileSync(SRC, 'utf8');

for (const [ref, [file, mime]] of Object.entries(ASSETS)) {
  const pattern = new RegExp(`url\\(['"]?${ref.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"]?\\)`, 'g');
  if (!pattern.test(css)) {
    console.error(`ERROR: ${SRC} no longer references ${ref} — update ASSETS.`);
    process.exit(1);
  }
  pattern.lastIndex = 0;
  css = css.replace(pattern, `url('${dataUri(file, mime)}')`);
}

// Sanity check: no relative asset references may survive, or the preview
// silently loses whatever is left behind.
const leftovers = css.match(/url\(['"]?\.\.\/assets\/[^)]+\)/g);
if (leftovers) {
  console.error('ERROR: unresolved asset references remain:\n  ' + leftovers.join('\n  '));
  process.exit(1);
}

// Drop the source's own leading comment blocks: the `@theme locmaf` directive
// and the "derived from" note are both restated in the banner below.
css = css.replace(/^(?:\/\*[\s\S]*?\*\/\s*)+/, '');

const banner = `/* @theme locmaf */
/*
 * LOCMAF Marp theme — SELF-CONTAINED build.
 * Generated by scripts/build-standalone-theme.mjs — DO NOT EDIT BY HAND.
 * Edit themes/locmaf.css and run \`npm run build:theme\` instead.
 *
 * The LevelOne font and both logos are embedded as data URIs so this single
 * file renders correctly in the VS Code Marp preview, which cannot resolve the
 * source theme's relative asset paths.
 *
 * Git-ignored on purpose — it carries a licensed brand font.
 */
`;

writeFileSync(OUT, banner + '\n' + css);
console.log(`Wrote ${OUT} (${(Buffer.byteLength(banner + css) / 1024).toFixed(0)} KB)`);
